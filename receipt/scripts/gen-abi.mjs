import { readFileSync, writeFileSync } from "node:fs";

const artifactPath = new URL("../../contracts/out/IAriaClearing.sol/IAriaClearing.json", import.meta.url);
const outPath = new URL("../src/abi.ts", import.meta.url);

const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));
const source = `// Generated by scripts/gen-abi.mjs from contracts/out/IAriaClearing.sol. Do not edit.\nexport const ariaClearingAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
writeFileSync(outPath, source);
console.log(`wrote ${abi.length} entries`);
